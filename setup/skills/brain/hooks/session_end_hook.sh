#!/usr/bin/env bash
# Brain Stop hook — auto-capture flow.
#
# Wire in ~/.claude/settings.json:
#   "hooks": {
#     "Stop": [
#       { "matcher": "*",
#         "hooks": [{
#           "type": "command",
#           "command": "$HOME/.claude/skills/brain/hooks/stop_hook.sh"
#         }]
#       }
#     ]
#   }
#
# Optional: gate with BRAIN_HOOK_ENABLED=1 to disable when developing
# the skill itself.

set -euo pipefail

# Enable gate (default ON; set BRAIN_HOOK_ENABLED=0 to disable)
if [[ "${BRAIN_HOOK_ENABLED:-1}" != "1" ]]; then
  exit 0
fi

BRAIN_SCRIPTS="$HOME/.claude/skills/brain/scripts"
VAULT_DIR="${BRAIN_VAULT:-$HOME/Documents/Knowledge}"
REPOS_DIR="$VAULT_DIR/repos"

# Vault must exist
[[ ! -d "$VAULT_DIR" ]] && exit 0

# Must be in a git repo
if ! git_root=$(git rev-parse --show-toplevel 2>/dev/null); then
  exit 0
fi

# Repo name → repos/<name>/ in vault
repo_name=$(basename "$git_root")
repo_dir="$REPOS_DIR/$repo_name"

# Try lowercase fallback
if [[ ! -d "$repo_dir" ]]; then
  repo_name=$(echo "$repo_name" | tr '[:upper:]' '[:lower:]')
  repo_dir="$REPOS_DIR/$repo_name"
fi

# If we don't have a tracked logbook for this repo, skip silently
[[ ! -d "$repo_dir" ]] && exit 0

# Dedup: skip if a pending file for this repo exists in last 10 min
mkdir -p "$VAULT_DIR/inbox"
recent_pending=$(find "$VAULT_DIR/inbox" -maxdepth 1 \
  -name "_pending-${repo_name}-*" -mmin -10 2>/dev/null | head -1)
if [[ -n "$recent_pending" ]]; then
  exit 0
fi

ts=$(date +%Y-%m-%d-%H%M)
pending_file="$VAULT_DIR/inbox/_pending-${repo_name}-${ts}.md"

# Generate the checkpoint draft
{
  echo "# Pending checkpoint — $repo_name @ $ts"
  echo
  echo "<!-- Auto-generated by /brain Stop hook."
  echo "     Review & edit '## Suggested attempts.md entry' below,"
  echo "     then approve with: /brain commit-checkpoint $(basename "$pending_file") -->"
  echo
  echo "## From git diff (last 24h)"
  echo
  bash "$BRAIN_SCRIPTS/lib/commit_diff_extract.sh" "$git_root" 2>/dev/null \
    || echo "(extractor failed)"
  echo
  echo "## From transcript (last hour)"
  echo
  python3 "$BRAIN_SCRIPTS/lib/transcript_extract.py" "$git_root" 2>/dev/null \
    || echo "(extractor failed)"
  echo
  echo "## Suggested attempts.md entry"
  echo
  echo "<!-- EDIT THIS SECTION before running /brain commit-checkpoint."
  echo "     Strip the fence and write a single attempts.md-shaped entry. -->"
  echo
  echo '```markdown'
  echo "## $(date '+%Y-%m-%d') · <one-line title summarizing this session>"
  echo "**What**: <what was tried in this session>"
  echo "**Outcome**: <shipped | blocked | abandoned | exploratory>"
  echo "**Why it worked / failed**: <reason — link to [[domain/pattern]] where applicable>"
  echo '```'
} > "$pending_file"

# Stop-hook output is captured by Claude Code; visible to user
echo "🧠 Brain captured a checkpoint: $(basename "$pending_file")"
echo "   Review with: /brain checkpoint review"
