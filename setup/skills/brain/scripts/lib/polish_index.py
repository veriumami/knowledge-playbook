#!/usr/bin/env python3
"""Regenerate SESSION_INDEX.md for one repo from its auto-logged sessions.

Deterministic and idempotent: parses repos/<name>/attempts.md (the mirror
written by session_autolog.sh) and emits a newest-first session table.
Records ONLY what the auto entries already contain (commits, file counts,
notes). Invents nothing. Safe to run repeatedly.

Usage: polish_index.py <repo_dir>
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

RE_HEAD = re.compile(r"^### session (.*?) <!-- auto sid:(.*?) -->")
RE_COMMIT = re.compile(r"^- (.*)")
RE_CHANGED = re.compile(r"\*\*Changed:\*\*\s*(\d+)")


def parse(src: Path) -> list[dict]:
    sessions: list[dict] = []
    cur: dict | None = None
    state: str | None = None
    for line in src.read_text().splitlines():
        m = RE_HEAD.match(line)
        if m:
            if cur:
                sessions.append(cur)
            cur = {"when": m.group(1).strip(), "sid": m.group(2).strip(),
                   "commits": [], "nfiles": 0, "note": ""}
            state = None
            continue
        if cur is None:
            continue
        if line.startswith("**Commits:**"):
            state = "commits"
            continue
        if line.startswith("**Changed:**"):
            mm = RE_CHANGED.search(line)
            cur["nfiles"] = int(mm.group(1)) if mm else 0
            state = "changed"
            continue
        if line.startswith("**Note:**"):
            cur["note"] = line.split("**Note:**", 1)[1].strip()
            state = None
            continue
        if state == "commits":
            cm = RE_COMMIT.match(line)
            if cm:
                cur["commits"].append(cm.group(1).strip())
            elif line.strip() == "":
                state = None
    if cur:
        sessions.append(cur)
    return sessions


def cell(s: str) -> str:
    return s.replace("|", "\\|").strip() or "—"


def summary(s: dict) -> str:
    if s["commits"]:
        # first real commit subject (strip leading short-sha)
        first = s["commits"][0]
        first = re.sub(r"^[0-9a-f]{7,40}\s+", "", first)
        return cell(first)
    if s["note"]:
        return cell(s["note"])
    return "(no commits)"


def main() -> int:
    if len(sys.argv) < 2:
        return 0
    repo_dir = Path(sys.argv[1])
    src = repo_dir / "attempts.md"
    if not src.exists():
        return 0
    sessions = parse(src)
    if not sessions:
        return 0
    out = [f"# Session Index — {repo_dir.name}",
           "_Auto-generated by brain polish from attempts.md. Regenerated nightly; do not hand-edit._",
           "",
           "| Session (newest first) | Commits | Files | Summary |",
           "|---|---|---|---|"]
    for s in sessions:
        out.append(f"| {cell(s['when'])} | {len(s['commits'])} | {s['nfiles']} | {summary(s)} |")
    out.append("")
    (repo_dir / "SESSION_INDEX.md").write_text("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
